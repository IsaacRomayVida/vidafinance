/**
 * Regenerates src/components/marketing/boardPlaceholders.ts: a tiny inline
 * copy of every board still, shown under the real photograph until it has
 * loaded (see BoardPhoto.tsx).
 *
 * Needs `cwebp` on the PATH (libwebp). Run it after a board still changes:
 *   node scripts/board-placeholders.mjs
 * boardPlaceholders.test.ts fails when a still used by a board has no entry.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/components/marketing/boardPlaceholders.ts');

/** Every still handed to <BoardPhoto still="…">. */
const STILLS = ['/images/brand/moment-school-walk.webp', '/images/brand/moment-clinic.webp'];
const WIDTH = 24;
const QUALITY = 30;

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'board-placeholders-'));
const entries = STILLS.map((still, i) => {
  const out = path.join(tmp, `${i}.webp`);
  execFileSync('cwebp', ['-quiet', '-q', String(QUALITY), '-resize', String(WIDTH), '0', path.join(ROOT, 'public', still), '-o', out]);
  const data = fs.readFileSync(out);
  console.log(`${still}: ${data.length} bytes`);
  return `  '${still}':\n    'data:image/webp;base64,${data.toString('base64')}',`;
});
fs.rmSync(tmp, { recursive: true, force: true });

fs.writeFileSync(
  OUT,
  `/**
 * GENERATED by scripts/board-placeholders.mjs — do not edit by hand.
 *
 * A ${WIDTH}px-wide copy of each board still, inlined so it costs no request.
 * BoardPhoto paints it under the photograph until the real file has loaded.
 */
export const BOARD_PLACEHOLDERS: Record<string, string> = {
${entries.join('\n')}
};
`,
);
